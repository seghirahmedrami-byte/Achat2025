const fs=require('fs'),vm=require('vm'),assert=require('node:assert/strict'),cp=require('child_process');
const context=vm.createContext({window:{},localStorage:{getItem:()=>null},sessionStorage:{getItem:()=>null},console});
vm.runInContext(fs.readFileSync('data.js','utf8'),context);
const html=fs.readFileSync('index.html','utf8');
vm.runInContext(html.match(/<script>([\s\S]*?)<\/script>/)[1],context);
const run=code=>vm.runInContext(code,context);
assert.equal(run('currentInvoices().length'),12);
assert.equal(run('currentInvoiceProductLines().length'),52);
assert.equal(run('currentProducts().length'),52);
assert.equal(run('Math.round(originalForInvoiceList(currentInvoices()).USD*100)'),6640168);
assert.equal(run('Math.round(originalForInvoiceList(currentInvoices()).EUR*100)'),10799776);
assert.equal(run('currentSuppliers().length'),5);
assert.equal(run('Math.round(currentInvoiceProductLines().reduce((s,r)=>s+r.line_total,0)*100)'),17439944);
assert.equal(run('currentInvoices().filter(i=>!i.date).length'),2);
assert.equal(run('currentInvoices().filter(i=>!i.invoice).length'),1);
run("state.year='Invoice 2025'");
assert.equal(run('currentInvoices().length'),40);
const originalContext=vm.createContext({window:{}});
vm.runInContext(cp.execFileSync('git',['show','HEAD:data.js'],{encoding:'utf8'}),originalContext);
const orig=originalContext.window.PURCHASE_DATA;
assert.deepEqual(JSON.parse(run('JSON.stringify(data.invoices.slice(0,43))')),JSON.parse(JSON.stringify(orig.invoices)));
assert.deepEqual(JSON.parse(run(`JSON.stringify(data.records.slice(0,${orig.records.length}))`)),JSON.parse(JSON.stringify(orig.records)));
const totals=run('JSON.stringify(originalForInvoiceList(currentInvoices()))');
for(const supplier of run('currentSuppliers()')) {
  const expected=orig.invoices.filter(i=>i.supplier===supplier.supplier && i.date.includes('2025')).reduce((s,i)=>s+i.total_amount,0);
  assert.ok(Math.abs(supplier.total_amount-expected)<0.001);
}
run("state.year='Invoice 2026';state.supplier='UM METAL CORPORATION'");
assert.equal(run('currentInvoices().length'),7);
assert.equal(run('Math.round(currentSuppliers()[0].total_amount*100)'),6088168);
run("state.currency='EUR'");
assert.equal(run('currentInvoices().length'),0);
console.log('PASS: 2026 counts and currency totals, printed amounts, missing fields, supplier/year/currency isolation, unchanged 2025 records. 2025 totals:',totals);
